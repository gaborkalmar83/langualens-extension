    def disc(p, rad, c): d.ellipse([p[0] - rad, p[1] - rad, p[0] + rad, p[1] + rad], fill=c)
    def ring(x, y, rad, f0, f1, w, c):
        if f1 > f0: d.arc([x - rad, y - rad, x + rad, y + rad], -90 + 360 * f0, -90 + 360 * f1, fill=c, width=int(w))
    def line(x0, y0, x1, y1, c, w=2): d.line([(x0, y0), (x1, y1)], fill=c, width=w)

    if L == 1:
        circ(cx, cy, r * 0.82, col("metal2")); circ(cx, cy, r * 0.54, col("metal2"))
        if v == 1:
            ring(cx, cy, r * 0.82, 0, mf, 6, col("accent")); ring(cx, cy, r * 0.54, 0, hf, 6, col("metal"))
        for i in range(12): disc(pt(TAU * i / 12, r * 0.82), r * 0.012, col("metal2"))
        disc(pt(TAU * hf, r * 0.54), r * 0.11, col("metal"))
        if v == 2: disc(pt(TAU * hf, r * 0.54), r * 0.05, col("bg"))
        disc(pt(TAU * mf, r * 0.82), r * 0.07, col("accent"))
        disc((cx, cy), r * 0.22, col("sub")); circ(cx, cy, r * 0.22, col("metal"))
        lab(cx, cy, "SMALL", str(day), col("txt"))
    elif L == 2:
        num(cx, cy - r * 0.40, "THAI", H, col("metal")); num(cx, cy + r * 0.40, "THAI", M, col("txt"))
        d.rectangle([cx - r * 0.7, cy - 2, cx - r * 0.3, cy + 3], fill=col("accent"))
        d.rectangle([cx + r * 0.3, cy - 2, cx + r * 0.7, cy + 3], fill=col("accent"))
        lab(cx, cy, "XTINY", date if v == 0 else f["mark"], col("accent"))
    elif L == 3:
        hx, hy, rs = cx, cy - r * 0.42, r * 0.30
        disc((hx, hy), rs, col("sub")); circ(hx, hy, rs, col("metal"))
        for k in range(12):
            a = TAU * k / 12
            line(hx + rs * .8 * math.sin(a), hy - rs * .8 * math.cos(a), hx + rs * .95 * math.sin(a), hy - rs * .95 * math.cos(a), col("metal"))
        ha = TAU * hf
        line(hx, hy, hx + rs * .62 * math.sin(ha), hy - rs * .62 * math.cos(ha), col("metal"), 6)
        sx, sy, ss = cx, cy + r * 0.46, r * 0.23
        disc((sx, sy), ss, col("sub")); circ(sx, sy, ss, col("metal"))
        if v == 1:
            disc((sx, sy), ss * 0.55, col("metal")); disc((sx - ss * 0.3, sy), ss * 0.5, col("sub"))
        elif v == 2:
            ring(sx, sy, ss * 0.78, 0.625, 1.375, ss * 0.16, col("metal2")); ring(sx, sy, ss * 0.78, 0.625, 0.625 + 0.75 * battery / 100, ss * 0.16, col("accent"))
            lab(sx, sy, "XTINY", str(battery), col("txt"))
        else:
            sa = TAU * sec / 60
            line(sx, sy, sx + ss * .8 * math.sin(sa), sy - ss * .8 * math.cos(sa), col("accent"), 4)
        bar(TAU * mf, -r * 0.12, r * 0.84, r * 0.018, col("hand")); disc((cx, cy), r * 0.045, col("hand"))
        lab(cx + r * 0.50, cy, "XTINY", date, col("txt"))
    elif L == 4:
        ring(cx, cy, r * 0.88, 0, 1, pw, col("metal2")); ring(cx, cy, r * 0.88, 0, mf, pw, col("accent"))
        ring(cx, cy, r * 0.70, 0, 1, pw, col("sub")); ring(cx, cy, r * 0.70, 0, hf, pw, col("metal"))
        num(cx, cy - r * 0.05, "NMED", H + ":" + M, col("txt")); lab(cx, cy + r * 0.30, "XTINY", date, col("metal"))
    elif L == 5:
        ww, wh = r * 0.74, r * 0.50
        d.rounded_rectangle([cx - ww / 2, cy - r * 0.62, cx + ww / 2, cy - r * 0.62 + wh], r * 0.06, fill=col("sub"), outline=col("metal"), width=4)
        num(cx, cy - r * 0.37, "HOT", H, col("txt"))
        ring(cx, cy, r * 0.80, 0.33, 0.67, 4, col("metal2"))
        for q in range(13):
            fa = TAU * (0.67 - 0.34 * q / 12)
            d.line([pt(fa, r * 0.76), pt(fa, r * 0.84)], fill=col("metal2"), width=2)
        disc(pt(TAU * (0.67 - 0.34 * mf), r * 0.80), r * 0.06, col("accent"))
        lab(cx, cy + r * 0.22, "MEDIUM", M, col("metal")); lab(cx, cy + r * 0.50, "XTINY", "MINUTES" if v == 0 else date, col("metal2"))
    elif L == 6:
        mw = "O'CLOCK"
        if 0 < m < 10: mw = "OH " + ONES[m]
        if 10 <= m < 20: mw = ONES[m]
        if m >= 20: mw = TENS[m // 10] + (" " + ONES[m % 10] if m % 10 else "")
        line(cx - r * 0.6, cy - r * 0.42, cx + r * 0.6, cy - r * 0.42, col("metal2"))
