"""Builds the ten watch face projects and their mock-ups from faces.json.
Usage: python3 gen.py"""
import hashlib, json, math, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FACES = json.load(open(os.path.join(HERE, "faces.json")))
DEVICES = ["fenix7", "fenix7s", "fenix7x", "fenix7pro", "fenix7spro", "fenix7xpro", "fenix843mm", "fenix847mm",
           "epix2", "epix2pro42mm", "epix2pro47mm", "epix2pro51mm", "fr165", "fr255", "fr265", "fr265s",
           "fr955", "fr965", "venu2", "venu2s", "venu2plus", "venu3", "venu3s", "vivoactive5"]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)


def mc(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    return "0x" + v


def project(f):
    d = os.path.join(HERE, f["slug"])
    uid = hashlib.md5(("maison-" + f["slug"]).encode()).hexdigest()
    products = "\n".join('            <iq:product id="%s"/>' % p for p in DEVICES)
    write(os.path.join(d, "manifest.xml"), """<?xml version="1.0"?>
<iq:manifest version="3" xmlns:iq="http://www.garmin.com/xml/connectiq">
    <iq:application id="%s" type="watchface" name="@Strings.AppName" entry="LuxApp" launcherIcon="@Drawables.LauncherIcon" minApiLevel="3.2.0">
        <iq:products>
%s
        </iq:products>
        <iq:permissions/>
        <iq:languages>
            <iq:language>eng</iq:language>
        </iq:languages>
    </iq:application>
</iq:manifest>
""" % (uid, products))
    write(os.path.join(d, "monkey.jungle"), "project.manifest = manifest.xml\nproject.typecheck = 0\n"
          "base.sourcePath = source;../common/source\n")
    write(os.path.join(d, "resources", "strings.xml"),
          '<resources>\n    <string id="AppName">%s</string>\n</resources>\n' % f["name"])
    write(os.path.join(d, "resources", "drawables.xml"),
          '<drawables>\n    <bitmap id="LauncherIcon" filename="launcher_icon.png"/>\n</drawables>\n')
    keys = ["bg", "pat", "pattern", "metal", "metal2", "txt", "accent", "sub", "hand", "lume", "hands", "index",
            "left", "right", "bottom", "date", "digital", "sweep"]
    rows = ['        :mark => "%s"' % f["mark"]] + ["        :%s => %s" % (k, mc(f[k])) for k in keys]
    write(os.path.join(d, "source", "Style.mc"),
          "// %s: %s\n// Generated by gen.py from faces.json.\nmodule Style {\n    const C = {\n%s\n    };\n}\n"
          % (f["name"], f["tag"], ",\n".join(rows)))
    return d


# ---------- mock-up renderer (mirrors common/source/LuxFace.mc) ----------
S = 832  # drawn large, scaled down for smooth edges
SERIF = "/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf"
SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def font(size, serif=False):
    p = SERIF if serif and os.path.exists(SERIF) else SANS
    return ImageFont.truetype(p, int(size)) if os.path.exists(p) else ImageFont.load_default()


def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render(f, hour=10, minute=9, sec=36, day=14, battery=82, steps=7421, hr=58, moon_p=0.36):
    cx = cy = r = S / 2
    im = Image.new("RGB", (S, S), rgb(f["bg"]))
    d = ImageDraw.Draw(im)
    col = lambda k: rgb(f[k])

    def pt(a, dist, o=0):
        return (cx + dist * math.sin(a) + o * math.cos(a), cy - dist * math.cos(a) + o * math.sin(a))

    def bar(a, d0, d1, hw, c):
        d.polygon([pt(a, d0, hw), pt(a, d1, hw), pt(a, d1, -hw), pt(a, d0, -hw)], fill=c)

    def text(x, y, size, s, c, serif=False):
        d.text((x, y), s, font=font(size, serif), fill=c, anchor="mm")

    p = f["pattern"]
    if p == 1:
        for i in range(72):
            a = 2 * math.pi * i / 72
            d.line([pt(a, r * 0.08), pt(a, r * 0.90)], fill=col("pat"), width=2)
    elif p == 2:
        for q in range(3, 18):
            rr = r * q * 0.05
            d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], outline=col("pat"), width=2)
    elif p == 3:
        step = r / 9
        for k in range(-18, 19):
            d.line([(cx + k * step - r, cy - r), (cx + k * step + r, cy + r)], fill=col("pat"), width=2)
            d.line([(cx + k * step + r, cy - r), (cx + k * step - r, cy + r)], fill=col("pat"), width=2)
    elif p == 4:
        seed = 11
        for s in range(60):
            seed = (seed * 73 + 41) % 997; sx = cx - r + seed * 2 * r / 997
            seed = (seed * 73 + 41) % 997; sy = cy - r + seed * 2 * r / 997
            rr = 4 if s % 9 == 0 else 2
            d.ellipse([sx - rr, sy - rr, sx + rr, sy + rr], fill=col("metal") if s % 6 == 0 else col("pat"))
    elif p == 6:
        for g, (gx0, gy0, gr0) in enumerate([(-0.30, -0.28, 0.26), (0.34, -0.20, 0.20), (0.30, 0.30, 0.24), (-0.36, 0.26, 0.16), (0.0, 0.0, 0.14)]):
            gx, gy, gr = cx + r * gx0, cy + r * gy0, r * gr0
            for k in (1, 0.82, 0.28):
                d.ellipse([gx - gr * k, gy - gr * k, gx + gr * k, gy + gr * k], outline=col("pat"), width=4)
            for sp in range(6):
                ga = math.pi * sp / 3 + g
                d.line([(gx + gr * 0.28 * math.sin(ga), gy - gr * 0.28 * math.cos(ga)),
                        (gx + gr * 0.82 * math.sin(ga), gy - gr * 0.82 * math.cos(ga))], fill=col("pat"), width=4)
    elif p == 5:
        gap = r / 8
        for v in range(-8, 9):
            d.line([(cx + v * gap, 0), (cx + v * gap, S)], fill=col("pat"), width=2)

    bw = r * 0.05
    d.ellipse([0, 0, S - 1, S - 1], outline=col("metal"), width=int(bw))
    e = bw + 4
    d.ellipse([e, e, S - 1 - e, S - 1 - e], outline=col("metal2"), width=2)
    for i in range(60):
        if i % 5:
            a = 2 * math.pi * i / 60
            d.line([pt(a, r * 0.86), pt(a, r * 0.90)], fill=col("metal2"), width=2)

    roman, arab = ["XII", "III", "VI", "IX"], ["12", "3", "6", "9"]
    st = f["index"]
    for h in range(12):
        a = 2 * math.pi * h / 12
        quarter = h % 3 == 0
        taken = (h == 3 and (f["right"] or f["date"])) or (h == 6 and f["bottom"]) or (h == 9 and f["left"])
        if f["digital"] and not quarter: continue
        if st == 2:
            g = pt(a, r * 0.78)
            for rr, c in ((r * (0.045 if quarter else 0.028), col("metal")), (r * (0.022 if quarter else 0.012), col("txt"))):
                d.ellipse([g[0] - rr, g[1] - rr, g[0] + rr, g[1] + rr], fill=c)
        elif st in (1, 3) and quarter and not taken and not f["digital"]:
            n = pt(a, r * 0.72)
            text(n[0], n[1], r * (0.20 if st == 1 else 0.24), roman[h // 3] if st == 1 else arab[h // 3], col("metal"), st == 1)
        else:
            inner = 0.80 if (taken and f["date"] and h == 3) else (0.68 if quarter else 0.73)
            bar(a, r * inner, r * 0.84, r * (0.028 if quarter else 0.014), col("metal"))
            if h == 0 and st == 0: bar(a, r * 0.68, r * 0.84, r * 0.008, col("bg"))

    text(cx, cy - r * (0.56 if f["digital"] else 0.38), r * 0.10, f["mark"], col("metal"), True)

    def sub(kind, x, y):
        if not kind: return
        rs = r * 0.23
        d.ellipse([x - rs, y - rs, x + rs, y + rs], fill=col("sub"))
        if kind == 2:
            mr = rs * 0.55
            d.ellipse([x - mr, y - mr, x + mr, y + mr], outline=col("metal2"), width=2)
            side, k = (1 if moon_p < 0.5 else -1), math.cos(2 * math.pi * moon_p)
            ts = [-math.pi / 2 + math.pi * i / 12 for i in range(13)]
            pts = [(x + side * mr * math.cos(t), y + mr * math.sin(t)) for t in ts]
            pts += [(x + side * k * mr * math.cos(t), y + mr * math.sin(t)) for t in reversed(ts)]
            d.polygon(pts, fill=col("metal"))
        d.ellipse([x - rs, y - rs, x + rs, y + rs], outline=col("metal"), width=2)
        if kind in (1, 3):
            fr = battery / 100 if kind == 1 else min(1, steps / 10000)
            label = str(battery) if kind == 1 else "%.1fK" % (steps / 1000)
            ra = rs * 0.78
            box = [x - ra, y - ra, x + ra, y + ra]
            d.arc(box, 135, 405, fill=col("metal2"), width=int(rs * 0.16))
            d.arc(box, 135, 135 + 270 * fr, fill=col("accent"), width=int(rs * 0.16))
            text(x, y, r * 0.10, label, col("txt"))
        elif kind == 4:
            text(x, y, r * 0.10, str(hr), col("txt"))
            q = rs * 0.09
            d.ellipse([x - q, y + rs * 0.68 - q, x + q, y + rs * 0.68 + q], fill=col("accent"))
        elif kind == 5:
            for i in range(12):
                a = 2 * math.pi * i / 12
                d.line([(x + rs * 0.78 * math.sin(a), y - rs * 0.78 * math.cos(a)),
                        (x + rs * 0.95 * math.sin(a), y - rs * 0.95 * math.cos(a))], fill=col("metal2"), width=2)
            sa = 2 * math.pi * sec / 60
            d.line([(x - rs * 0.2 * math.sin(sa), y + rs * 0.2 * math.cos(sa)),
                    (x + rs * 0.8 * math.sin(sa), y - rs * 0.8 * math.cos(sa))], fill=col("accent"), width=4)
            d.ellipse([x - 5, y - 5, x + 5, y + 5], fill=col("metal"))

    sub(f["left"], cx - r * 0.44, cy)
    sub(f["right"], cx + r * 0.44, cy)
    sub(f["bottom"], cx, cy + r * 0.44)

    if f["digital"]:
        text(cx, cy - r * 0.34, r * 0.10, "SAT %d NOV" % day, col("txt"))
        text(cx, cy - r * 0.04, r * 0.46, "%02d:%02d" % (hour, minute), col("metal"), True)
    else:
        if f["date"]:
            fh = r * 0.15; w2 = fh * 1.5; x = cx + r * 0.62 - w2 / 2
            d.rectangle([x, cy - fh / 2, x + w2, cy + fh / 2], fill=col("sub"), outline=col("metal"), width=2)
            text(x + w2 / 2, cy, r * 0.11, str(day), col("txt"))

        def hand(a, ln, hw):
            tail = r * 0.10
            if f["hands"] == 1:
                pts = [pt(a, -tail, hw * .7), pt(a, ln, hw * .7), pt(a, ln, -hw * .7), pt(a, -tail, -hw * .7)]
            elif f["hands"] == 2:
                pts = [pt(a, -tail, hw * .5), pt(a, ln * .82, hw), pt(a, ln, 0), pt(a, ln * .82, -hw), pt(a, -tail, -hw * .5)]
            else:
                pts = [pt(a, -tail, 0), pt(a, ln * .28, hw), pt(a, ln, 0), pt(a, ln * .28, -hw)]
            d.polygon(pts, fill=col("hand"))
            if f["lume"]: bar(a, ln * .35, ln * .78, hw * .35, rgb(f["lume"]))

        hand(2 * math.pi * ((hour % 12) + minute / 60) / 12, r * 0.50, r * 0.055)
        hand(2 * math.pi * minute / 60, r * 0.80, r * 0.042)
        if f["sweep"]:
            sa = 2 * math.pi * sec / 60
            p0, p1 = pt(sa, -r * 0.18), pt(sa, r * 0.84)
            d.line([p0, p1], fill=col("accent"), width=4)
            q = r * 0.03
            d.ellipse([p0[0] - q, p0[1] - q, p0[0] + q, p0[1] + q], fill=col("accent"))
        for rr, c in ((r * 0.05, col("hand")), (r * 0.02, col("bg"))):
            d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=c)

    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).ellipse([0, 0, S - 1, S - 1], fill=255)
    out = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    out.paste(im, (0, 0), mask)
    return out


def sheet(faces, path, cols=5):
    size, pad, label = 416, 28, 70
    rows = (len(faces) + cols - 1) // cols
    im = Image.new("RGB", (cols * (size + pad) + pad, rows * (size + pad + label) + pad), (14, 14, 16))
    sd = ImageDraw.Draw(im)
    for i, f in enumerate(faces):
        small = Image.open(os.path.join(HERE, "design", f["slug"] + ".png"))
        x = pad + (i % cols) * (size + pad)
        y = pad + (i // cols) * (size + pad + label)
        im.paste(small, (x, y), small)
        name = f["name"] if f["name"].startswith("No.") else "No. %d %s" % (f["num"], f["name"])
        sd.text((x + size / 2, y + size + 24), name, font=font(28, True), fill=(235, 225, 200), anchor="mm")
        sd.text((x + size / 2, y + size + 54), f["tag"], font=font(14), fill=(150, 150, 150), anchor="mm")
    im.save(path)


def main():
    for f in FACES:
        d = project(f)
        face = render(f)
        face.resize((80, 80), Image.LANCZOS).save(os.path.join(d, "resources", "launcher_icon.png"))
        face.resize((416, 416), Image.LANCZOS).save(os.path.join(HERE, "design", f["slug"] + ".png"))
    sheet(FACES[:10], os.path.join(HERE, "design", "collection.png"))
    sheet(FACES[10:], os.path.join(HERE, "design", "collection-2.png"))
    print("built", len(FACES), "faces")


if __name__ == "__main__":
    main()
